//! `SessionStart` registration: the manifest that enables the compiled-in rule,
//! and a bridge module that runs it for a dispatcher that reads no manifest
//! (the Bun dispatcher, until #425). A usable manifest shadows the bridge in
//! the native dispatcher, so the rule runs once either way.

use std::fs::{self, OpenOptions};
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::time::{Duration, SystemTime};

use toolu_protocol::exit::Exit;
use toolu_protocol::host::Host;
use toolu_runtime::cli::Outcome;
use toolu_runtime::env::Env;
use toolu_runtime::host::roots::Roots;
use toolu_runtime::invocation::current_exe;
use toolu_runtime::registry::manifest::ModuleManifest;
use toolu_runtime::registry::{ModuleKind, RegistryEvent, event_dir, file_name};

use crate::file::has_extension;
use crate::rule::{NAME, SPEC};

/// Set in the bridge's child so a bridge reached again from the native walk exits.
pub(crate) const BRIDGE_GUARD: &str = "TOOLU_TS_QUALITY_NATIVE";

/// `find -mmin +1`: a concurrent `SessionStart`'s in-flight tmp is left alone.
const RESIDUE_AGE: Duration = Duration::from_secs(60);

/// `text` as one single-quoted shell word.
fn quoted(text: &str) -> String {
  format!("'{}'", text.replace('\'', r"'\''"))
}

/// The bridge module, running `bin` for a TypeScript-looking payload.
pub(crate) fn bridge_script(bin: &Path) -> String {
  format!(
    "# Generated by `toolu ts-quality hook register` each session: runs the native rule\n\
     # for a dispatcher that reads no manifest.\n\
     [ -n \"${{{BRIDGE_GUARD}:-}}\" ] && exit 0\n\
     case \"${{input:-}}${{CLAUDE_FILE_PATHS:-}}\" in *.ts*) ;; *) exit 0 ;; esac\n\
     bin={}\n\
     [ -x \"$bin\" ] || bin=$(command -v toolu) || {{ echo 'ts-quality: toolu not found; TypeScript checks skipped' >&2; exit 1; }}\n\
     {BRIDGE_GUARD}=1 exec \"$bin\" ts-quality hook post-tools --event PostToolUse\n",
    quoted(&bin.to_string_lossy())
  )
}

fn manifest_body() -> Result<Vec<u8>, String> {
  let manifest = ModuleManifest {
    version: 1,
    spec: SPEC.to_owned(),
    name: NAME.to_owned(),
    event: RegistryEvent::ToolPost,
    matcher: "*".to_owned(),
  };
  let mut body = serde_json::to_vec(&manifest).map_err(|error| error.to_string())?;
  body.push(b'\n');
  Ok(body)
}

/// Write `body` to `target` atomically unless it already holds exactly that.
fn write_if_changed(target: &Path, body: &[u8]) -> Result<(), String> {
  if fs::read(target).is_ok_and(|existing| existing == body) {
    return Ok(());
  }
  let dir = target.parent().unwrap_or(target);
  let mut temporary =
    tempfile::NamedTempFile::new_in(dir).map_err(|error| format!("{}: {error}", dir.display()))?;
  temporary
    .write_all(body)
    .map_err(|error| format!("{}: {error}", target.display()))?;
  temporary
    .persist(target)
    .map_err(|error| format!("{}: {error}", target.display()))?;
  Ok(())
}

fn is_residue(name: &str) -> bool {
  name.contains(".js.tmp.") || name.contains(".sh.tmp.")
}

fn old_enough(path: &Path) -> bool {
  fs::symlink_metadata(path)
    .and_then(|meta| meta.modified())
    .is_ok_and(|when| {
      SystemTime::now()
        .duration_since(when)
        .is_ok_and(|age| age > RESIDUE_AGE)
    })
}

/// Remove this plugin's other `.js`/`.sh` modules and aged tmp residue from
/// `dir`; whether the old `.js` module was among them.
fn prune(dir: &Path, keep: &Path) -> Result<bool, String> {
  let Ok(list) = fs::read_dir(dir) else {
    return Ok(false);
  };
  let old = file_name(SPEC, NAME, ModuleKind::Esm).map_err(|error| error.0)?;
  let mut migrated = false;
  for entry in list.flatten() {
    let name = entry.file_name().to_string_lossy().into_owned();
    let path = entry.path();
    if !name.starts_with(&format!("{SPEC}__")) || path == keep {
      continue;
    }
    let stale = if is_residue(&name) {
      old_enough(&path)
    } else {
      has_extension(&name, &["js", "sh"])
        && fs::metadata(&path).is_ok_and(|meta| meta.is_file())
    };
    if stale {
      fs::remove_file(&path).map_err(|error| format!("{}: {error}", path.display()))?;
      migrated |= name == old;
    }
  }
  Ok(migrated)
}

fn report(env: &Env, target: &Path) -> Result<(), String> {
  let Some(report) = env.get("TOOLU_STARTUP_REPORT") else {
    return Ok(());
  };
  let record = serde_json::json!({
    "kind": "native-registry",
    "spec": SPEC,
    "name": NAME,
    "event": RegistryEvent::ToolPost,
    "matcher": "*",
    "target": target,
  });
  let mut line = record.to_string().into_bytes();
  line.push(b'\n');
  OpenOptions::new()
    .append(true)
    .open(report)
    .and_then(|mut output| output.write_all(&line))
    .map_err(|error| format!("cannot write startup report {report}: {error}"))
}

fn sync(env: &Env, roots: &Roots, bin: &Path) -> Result<bool, String> {
  let post = event_dir(roots, RegistryEvent::ToolPost);
  fs::create_dir_all(&post).map_err(|error| format!("{}: {error}", post.display()))?;
  let manifest = post.join(file_name(SPEC, NAME, ModuleKind::Manifest).map_err(|error| error.0)?);
  let bridge = post.join(file_name(SPEC, NAME, ModuleKind::Bash).map_err(|error| error.0)?);
  write_if_changed(&manifest, &manifest_body()?)?;
  write_if_changed(&bridge, bridge_script(bin).as_bytes())?;
  let pre = event_dir(roots, RegistryEvent::ToolPre);
  let migrated = prune(&post, &bridge)? | prune(&pre, &bridge)?;
  report(env, &manifest)?;
  Ok(migrated)
}

/// Publish the manifest and bridge, and remove this plugin's Bun module.
pub fn register(env: &Env, host: Host) -> Outcome {
  let roots = Roots::new(env.clone(), Some(host));
  let bin = current_exe().unwrap_or_else(|| PathBuf::from("toolu"));
  match sync(env, &roots, &bin) {
    Ok(migrated) => Outcome {
      exit: Exit::Success,
      stdout: migrated.then(|| {
        serde_json::json!({
          "systemMessage": "ts-quality's Bun module was replaced by its native rule in toolu."
        })
        .to_string()
      }),
      stderr: None,
    },
    Err(error) => Outcome {
      exit: Exit::Success,
      stdout: Some(
        serde_json::json!({ "systemMessage": format!("ts-quality registration failed: {error}") })
          .to_string(),
      ),
      stderr: None,
    },
  }
}

