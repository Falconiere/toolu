use super::{print, run};
use crate::Verdict;
use crate::options::Options;
use crate::task_options::test_root;

const PRE_TOOL_USE: &str =
  include_str!("../../../core/protocol/src/tests/fixtures/launcher-pre-tool-use.txt");

fn options(args: &[&str], timeout_ms: Option<&str>, resolver: bool) -> Options {
  Options {
    root: test_root(),
    files: args.iter().map(std::path::PathBuf::from).collect(),
    timeout_ms: timeout_ms.map(str::to_owned),
    resolver,
    ..Options::default()
  }
}

const PRE: [&str; 3] = ["toolu", "PreToolUse", "pre-tools"];

#[test]
fn a_known_plugin_entry_prints() {
  assert_eq!(run(&options(&PRE, None, false)).unwrap(), Verdict::Clean);
  assert_eq!(run(&options(&PRE, None, true)).unwrap(), Verdict::Clean);
}

#[test]
fn the_entry_is_the_muse_argv_with_the_default_timeout() {
  assert_eq!(
    print(&options(&PRE, None, false)).unwrap(),
    "{\n  \"id\": \"pre-tools\",\n  \"event\": \"PreToolUse\",\n  \"command\": [\n    \
     \"/bin/sh\",\n    \"hooks/muse/pre-tools\"\n  ],\n  \"timeoutMs\": 60000\n}"
  );
  let shorter = print(&options(&PRE, Some("30000"), false)).unwrap();
  assert!(shorter.ends_with("\"timeoutMs\": 30000\n}"), "{shorter}");
}

#[test]
fn the_resolver_is_the_launcher_rooted_at_muse_plugin_root() {
  let launcher = PRE_TOOL_USE.replace("${CLAUDE_PLUGIN_ROOT}", "${MUSE_PLUGIN_ROOT}");
  assert_eq!(
    print(&options(&PRE, None, true)).unwrap(),
    format!(
      "# Generated by cargo xtask print-muse-hook toolu PreToolUse pre-tools; do not edit.\n\
       {launcher}"
    )
  );
}

#[test]
fn bad_timeouts_events_names_plugins_and_arity_are_errors() {
  for timeout in ["0", "600001", "abc", "-1", "1.5"] {
    assert!(
      print(&options(&PRE, Some(timeout), false)).is_err(),
      "{timeout}"
    );
  }
  let bad = |args: &[&str]| print(&options(args, None, false)).unwrap_err();
  assert!(bad(&["toolu", "Notification", "pre-tools"]).starts_with("event must be a Muse event"));
  assert!(bad(&["toolu", "PreToolUse", "Bad_Name"]).contains("hook name"));
  assert_eq!(
    bad(&["no-such-plugin", "PreToolUse", "x"]),
    "no plugins/no-such-plugin directory"
  );
  assert_eq!(
    bad(&["toolu", "PreToolUse"]),
    "print-muse-hook needs <plugin> <Event> <name>"
  );
}
