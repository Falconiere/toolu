//! Path and committed header noise rules.

use super::parse::Status;

/// Committed header bytes read for a generator notice.
pub(super) const HEADER_BYTES: usize = 8192;
/// Leading lines that may carry a generator notice.
pub(super) const HEADER_LINES: usize = 5;

/// Classify common lockfile, vendored, build, and generated paths. Only
/// directory components name a vendored, build, or generated tree.
pub(super) fn path_noise(path: &str) -> Option<&'static str> {
  let (dirs, name) = path.rsplit_once('/').unwrap_or(("", path));
  if matches!(
    name,
    "Cargo.lock"
      | "package-lock.json"
      | "pnpm-lock.yaml"
      | "yarn.lock"
      | "bun.lock"
      | "bun.lockb"
      | "poetry.lock"
      | "uv.lock"
      | "Gemfile.lock"
      | "Pipfile.lock"
      | "go.sum"
      | "composer.lock"
      | "npm-shrinkwrap.json"
      | "deno.lock"
      | "flake.lock"
      | "Podfile.lock"
      | "pubspec.lock"
      | "mix.lock"
      | "Package.resolved"
      | "gradle.lockfile"
      | "packages.lock.json"
  ) {
    return Some("lockfile");
  }
  if dirs
    .split('/')
    .any(|part| matches!(part, "vendor" | "node_modules" | "third_party"))
  {
    return Some("vendored");
  }
  let top_dir = dirs.split('/').next().unwrap_or("");
  if matches!(
    top_dir,
    "target" | "dist" | "build" | ".next" | "out" | "coverage"
  ) {
    return Some("build output");
  }
  if dirs.split('/').any(|part| part == "generated")
    || name.contains(".generated.")
    || name.ends_with(".min.js")
  {
    return Some("generated");
  }
  None
}

/// Path noise of one status; a rename is noise only when its source path was noise too.
pub(super) fn status_noise(status: &Status) -> Option<&'static str> {
  path_noise(&status.path).filter(|_| {
    status
      .old_path
      .as_deref()
      .is_none_or(|old_path| path_noise(old_path).is_some())
  })
}

/// Recognize a generator notice on one of the first committed lines, such as
/// `// @generated` or `// Code generated by x. DO NOT EDIT.`; prose elsewhere
/// that merely mentions either phrase is not a notice.
pub(super) fn header_generated(blob: &[u8]) -> bool {
  let header = blob.get(..HEADER_BYTES).unwrap_or(blob);
  String::from_utf8_lossy(header)
    .lines()
    .take(HEADER_LINES)
    .any(generator_notice)
}

fn generator_notice(line: &str) -> bool {
  let line = line.trim_start();
  let line = line
    .strip_prefix("//")
    .or_else(|| line.strip_prefix('#'))
    .or_else(|| line.strip_prefix("/*"))
    .or_else(|| line.strip_prefix("<!--"))
    .unwrap_or(line)
    .trim_start_matches('*')
    .trim_start()
    .to_ascii_lowercase();
  line.starts_with("@generated")
    || (line.starts_with("code generated") && line.contains("do not edit"))
    || (line.starts_with("generated") && line.contains("do not edit"))
    || (line.starts_with("do not edit") && line.contains("generated"))
}

