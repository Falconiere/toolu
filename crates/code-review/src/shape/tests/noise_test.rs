use super::{header_generated, path_noise};

#[test]
fn noise_recognizes_paths_and_committed_header_markers() {
  assert_eq!(path_noise("pkg/Cargo.lock"), Some("lockfile"));
  assert_eq!(path_noise("web/deno.lock"), Some("lockfile"));
  assert_eq!(path_noise("npm-shrinkwrap.json"), Some("lockfile"));
  assert_eq!(path_noise("vendor/lib.rs"), Some("vendored"));
  assert_eq!(path_noise("target/app"), Some("build output"));
  assert_eq!(path_noise("src/parser.generated.rs"), Some("generated"));
  assert_eq!(path_noise("src/lib.rs"), None);
  assert!(header_generated(
    b"// DO NOT EDIT: generated file\nfn f() {}"
  ));
  assert!(!header_generated(b"fn f() {}"));
}

#[test]
fn noise_ignores_file_names_and_prose_that_only_mention_markers() {
  assert_eq!(path_noise("scripts/build"), None);
  assert_eq!(path_noise("out"), None);
  assert_eq!(path_noise("web/dist/app.js"), None);
  assert_eq!(path_noise("src/build/module.rs"), None);
  assert_eq!(
    path_noise("fixtures/epic/baseline/state/out/state.json"),
    None
  );
  assert!(!header_generated(b"//! Skips files marked @generated\n"));
  assert!(!header_generated(
    b"fn a() {}\n\n\n\n\n// Generated by x; do not edit.\n"
  ));
  assert!(!header_generated(b"// Do not edit this list by hand.\n"));
}
