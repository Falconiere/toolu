//! What `setup` generates: the Lima file of the VM and the script that installs
//! the toolchain inside it. Both are content in Rust, never files under
//! `plugins/`; the values they need are quoted (the YAML) or passed as
//! arguments (the script), never spliced into shell text.
//!
//! The image comes from Lima's own `template:_images/debian-13`: it pins dated
//! Debian 13 cloud images with digests and falls back to the latest release
//! once a dated one is gone, and unlike `template:debian-13` it adds no mount of
//! the user's home directory. The tool pins match `release-native.yml` (a test
//! in this crate keeps them equal).

use std::path::PathBuf;

use crate::facts::Os;

/// The Lima base the VM starts from unless `sandbox.template` names another.
pub(crate) const IMAGE_BASE: &str = "template:_images/debian-13";

/// Where the guest keeps build output, temporary files and clones: its own disk,
/// never the shared mount.
pub(crate) const GUEST_CACHE: &str = "/var/cache/toolu-sandbox";

/// The VM to create.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct VmSpec {
  /// CPUs.
  pub(crate) cpus: u32,
  /// Memory in GiB.
  pub(crate) memory_gib: u32,
  /// Disk in GiB.
  pub(crate) disk_gib: u32,
  /// The Lima template the file builds on.
  pub(crate) base: String,
  /// Host directories mounted writable at the same path.
  pub(crate) mounts: Vec<PathBuf>,
}

/// The Lima file of `spec` for a host running `os`, by toolu `version`.
pub(crate) fn lima_yaml(spec: &VmSpec, os: Os, version: &str) -> String {
  let mut lines = vec![
    format!(
      "# Generated by toolu sandbox {version}; change it with `toolu config set sandbox.<key>`."
    ),
    "minimumLimaVersion: \"2.0.0\"".to_owned(),
    "base:".to_owned(),
    format!("- {}", quoted(&spec.base)),
  ];
  if os == Os::Macos {
    lines.push("vmType: \"vz\"".to_owned());
    lines.push("mountType: \"virtiofs\"".to_owned());
  }
  lines.extend([
    "containerd:".to_owned(),
    "  system: false".to_owned(),
    "  user: false".to_owned(),
    format!("cpus: {}", spec.cpus),
    format!("memory: \"{}GiB\"", spec.memory_gib),
    format!("disk: \"{}GiB\"", spec.disk_gib),
    "mounts:".to_owned(),
  ]);
  for mount in &spec.mounts {
    lines.push(format!("- location: {}", quoted(&mount.to_string_lossy())));
    lines.push("  writable: true".to_owned());
  }
  lines.join("\n") + "\n"
}

/// A YAML double-quoted scalar: a JSON string is one.
fn quoted(text: &str) -> String {
  serde_json::Value::from(text).to_string()
}

/// The provisioning script, run in the project root as the guest user:
/// `bash -euo pipefail -c PROVISION toolu-sandbox-setup <toolu version>
/// <guest cache> <git name> <git email>`. Every step is skipped when its result
/// is already there, so a second `setup` only upgrades what changed.
pub(crate) const PROVISION: &str = r#"version=$1 cache=$2 name=$3 email=$4
say() { printf 'toolu-sandbox: %s\n' "$*"; }
say "cache directories"
sudo install -d -o "$(id -u)" -g "$(id -g)" "$cache" "$cache/target" "$cache/tmp" "$cache/work"
mkdir -p "$HOME/.local/bin"
say "system packages"
need=""
for pkg in build-essential pkg-config git curl ca-certificates bubblewrap socat ripgrep mold jq gh xz-utils python3; do
  dpkg-query -W -f='${Status}' "$pkg" 2>/dev/null | grep -q 'install ok installed' || need="$need $pkg"
done
if [ -n "$need" ]; then
  sudo DEBIAN_FRONTEND=noninteractive apt-get -qq update
  sudo DEBIAN_FRONTEND=noninteractive apt-get -qq install -y --no-install-recommends $need
fi
say "rust"
if [ ! -x "$HOME/.cargo/bin/rustup" ]; then
  curl --proto '=https' --tlsv1.2 -fsSL https://sh.rustup.rs | sh -s -- -y --profile minimal --default-toolchain stable -c rustfmt -c clippy
fi
. "$HOME/.cargo/env"
if [ -f rust-toolchain.toml ] || [ -f rust-toolchain ]; then
  rustup toolchain install
fi
say "cargo tools"
if ! command -v cargo-binstall >/dev/null 2>&1; then
  curl -fsSL "https://github.com/cargo-bins/cargo-binstall/releases/download/v1.26.1/cargo-binstall-$(uname -m)-unknown-linux-musl.tgz" | tar -xz -C "$HOME/.cargo/bin"
fi
cargo binstall --no-confirm --locked cargo-deny@0.20.2 cargo-machete@0.9.2 cargo-llvm-cov@0.9.1 cargo-nextest@0.9.146
say "node 22"
case "$(node --version 2>/dev/null || true)" in
  v22.*) ;;
  *)
    arch=$(dpkg --print-architecture)
    [ "$arch" = amd64 ] && arch=x64
    base=https://nodejs.org/dist/latest-v22.x
    tmp=$(mktemp -d)
    curl -fsSL -o "$tmp/SHASUMS256.txt" "$base/SHASUMS256.txt"
    file=$(grep -E " node-v22\.[0-9.]+-linux-$arch\.tar\.xz$" "$tmp/SHASUMS256.txt" | awk '{print $2}')
    curl -fsSL -o "$tmp/$file" "$base/$file"
    (cd "$tmp" && grep " $file\$" SHASUMS256.txt | sha256sum -c --quiet -)
    sudo tar -xJf "$tmp/$file" -C /usr/local --strip-components=1
    rm -rf "$tmp"
    ;;
esac
sudo npm config --global set update-notifier false
say "ast-grep"
case "$(ast-grep --version 2>/dev/null || true)" in
  "ast-grep 0.50.0") ;;
  *) sudo npm install -g --no-fund --no-audit @ast-grep/cli@0.50.0 ;;
esac
say "git identity"
git config --global user.name >/dev/null || git config --global user.name "$name"
git config --global user.email >/dev/null || git config --global user.email "$email"
say "toolu $version"
if [ "$("$HOME/.local/bin/toolu" --version 2>/dev/null || true)" != "toolu $version" ]; then
  installer=$(mktemp)
  curl -fsSL -o "$installer" https://get.toolu.sh/pkg/toolu/install
  if ! bash "$installer" --version "v$version" --install-dir "$HOME/.local/bin"; then
    say "toolu v$version is not released; installing the newest release"
    bash "$installer" --install-dir "$HOME/.local/bin"
  fi
  rm -f "$installer"
fi
say "done"
"#;

