use super::{DEFAULT_TIMEOUT_MS, MAX_TIMEOUT_MS, RESOLVER_DIR, hook, is_event};
use crate::launcher::Target;

const PRE_TOOL_USE: &str = include_str!("../../tests/fixtures/launcher-pre-tool-use.txt");
const SESSION_START: &str = include_str!("../../tests/fixtures/launcher-session-start.txt");

fn target<'a>(plugin: &'a str, event: &'a str, name: &'a str) -> Target<'a> {
  Target {
    plugin,
    event,
    name,
  }
}

#[test]
fn the_entry_runs_the_per_hook_resolver_with_bin_sh() {
  let generated = hook(
    &target("toolu", "PreToolUse", "pre-tools"),
    DEFAULT_TIMEOUT_MS,
  )
  .unwrap();
  let entry = serde_json::to_string_pretty(&generated.entry).unwrap();
  assert_eq!(
    entry,
    "{\n  \"id\": \"pre-tools\",\n  \"event\": \"PreToolUse\",\n  \"command\": [\n    \
     \"/bin/sh\",\n    \"hooks/muse/pre-tools\"\n  ],\n  \"timeoutMs\": 60000\n}"
  );
  assert_eq!(generated.resolver_path, "hooks/muse/pre-tools");
  assert!(generated.resolver_path.starts_with(RESOLVER_DIR));
}

#[test]
fn the_resolver_is_the_claude_launcher_rooted_at_muse_plugin_root() {
  for (event, name, golden) in [
    ("PreToolUse", "pre-tools", PRE_TOOL_USE),
    ("SessionStart", "session-start", SESSION_START),
  ] {
    let generated = hook(&target("toolu", event, name), DEFAULT_TIMEOUT_MS).unwrap();
    let launcher = golden.replace("${CLAUDE_PLUGIN_ROOT}", "${MUSE_PLUGIN_ROOT}");
    assert_eq!(
      generated.resolver,
      format!(
        "# Generated by cargo xtask print-muse-hook toolu {event} {name}; do not edit.\n\
         {launcher}\n"
      )
    );
    assert!(!generated.resolver.contains("CLAUDE_PLUGIN_ROOT"));
  }
}

#[test]
fn another_plugin_names_itself_in_the_argv_and_the_advisory() {
  let generated = hook(
    &target("statusline", "SessionStart", "session-start"),
    DEFAULT_TIMEOUT_MS,
  )
  .unwrap();
  assert!(
    generated
      .resolver
      .contains("statusline hook session-start --event SessionStart")
  );
  assert!(generated.resolver.contains("statusline plugin: no usable"));
}

#[test]
fn timeouts_are_bounded_in_milliseconds() {
  let pre = target("toolu", "PreToolUse", "pre-tools");
  for timeout in [1, 30_000, MAX_TIMEOUT_MS] {
    assert_eq!(hook(&pre, timeout).unwrap().entry.timeout_ms, timeout);
  }
  for timeout in [0, MAX_TIMEOUT_MS + 1] {
    let err = hook(&pre, timeout).unwrap_err();
    assert_eq!(
      err,
      format!("timeoutMs must be 1 to 600000 milliseconds, got {timeout}")
    );
  }
}

#[test]
fn only_muse_events_toolu_handles_are_accepted() {
  for event in [
    "PreToolUse",
    "PostToolUse",
    "PermissionRequest",
    "SessionStart",
    "SessionEnd",
    "UserPromptSubmit",
    "PreCompact",
  ] {
    assert!(is_event(event), "{event}");
    assert!(hook(&target("toolu", event, "x"), DEFAULT_TIMEOUT_MS).is_ok());
  }
  for event in [
    "Notification",
    "Stop",
    "SubagentStop",
    "PostToolUseFailure",
    "preToolUse",
  ] {
    assert!(!is_event(event), "{event}");
    let err = hook(&target("toolu", event, "x"), DEFAULT_TIMEOUT_MS).unwrap_err();
    assert!(
      err.starts_with("event must be a Muse event toolu handles"),
      "{err}"
    );
    assert!(err.contains("PreToolUse, PostToolUse"), "{err}");
  }
}

#[test]
fn bad_names_are_errors() {
  for (plugin, name) in [("Bad_Plugin", "x"), ("toolu", "Bad_Name"), ("toolu", "")] {
    assert!(
      hook(&target(plugin, "PreToolUse", name), DEFAULT_TIMEOUT_MS).is_err(),
      "{plugin} {name}"
    );
  }
}
