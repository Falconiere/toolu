use serde_json::json;

use super::{FILE, hooks_of, shim};
use crate::install::missing_message;
use crate::opencode::Hook;

#[test]
fn the_shim_fills_every_placeholder_with_json() {
  let text = shim("toolu", &[Hook::ToolAfter, Hook::ToolBefore], true).unwrap();
  assert!(!text.contains("__"), "{text}");
  assert!(text.contains("const PLUGIN = \"toolu\";"));
  assert!(text.contains("const HOOKS = [\"tool.execute.before\",\"tool.execute.after\"];"));
  assert!(text.contains("const CATALOG = true;"));
  let missing = serde_json::to_string(&missing_message("toolu")).unwrap();
  assert!(text.contains(&format!("const MISSING = {missing};")));
  assert!(
    text.starts_with("// Generated by `toolu plugins install --host opencode` for the \"toolu\"")
  );
  assert_eq!(FILE, "server.js");
}

#[test]
fn a_plugin_without_hooks_or_catalog_gets_an_empty_list() {
  let text = shim("sandbox", &[], false).unwrap();
  assert!(text.contains("const HOOKS = [];"));
  assert!(text.contains("const CATALOG = false;"));
}

#[test]
fn the_shim_refuses_a_bad_plugin_name() {
  for name in ["", "Toolu", "a b", "x\"y"] {
    assert!(shim(name, &[], false).is_err(), "{name:?}");
  }
}

#[test]
fn the_shim_fails_closed_and_never_holds_policy() {
  let text = shim("toolu", &Hook::ALL, true).unwrap();
  for needle in [
    "throw new Error(reply.reason",
    "\"opencode\", \"bridge\", \"--event\"",
    "\"--hook-protocol\"",
    "process.env.TOOLU_BIN",
    "ctx.session.instructions.entry.put",
    "await keep(event.sessionID, \"compaction\", reply.context);",
  ] {
    assert!(text.contains(needle), "{needle}");
  }
}

#[test]
fn hooks_of_reads_the_events_opencode_has() {
  let doc = json!({"hooks": {"SessionStart": [], "PostToolUse": [], "SessionEnd": [],
    "PreToolUse": [], "PermissionRequest": []}});
  assert_eq!(
    hooks_of(&doc),
    [Hook::SessionStart, Hook::ToolBefore, Hook::ToolAfter]
  );
  assert_eq!(hooks_of(&json!({})), []);
  assert_eq!(hooks_of(&json!({"hooks": []})), []);
}
