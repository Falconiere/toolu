//! The Muse hook entry (#546), checked by `cargo xtask check-hooks`. Muse runs a
//! hook as an argv with no shell, and a missing `toolu` there fails open, so each
//! entry runs `/bin/sh` on its own resolver file, `hooks/muse/<name>`. The file
//! holds the `hooks.json` launcher with `--plugin-root "${MUSE_PLUGIN_ROOT}"`, so
//! binary resolution, the skew check and the fail-closed classes are the same as
//! on Claude Code. Muse refuses a relative argv word containing `/` unless it
//! names a package file, and two hooks may not share one, hence one file per hook.

use serde::Serialize;

use super::{DEFAULT_TIMEOUT, MAX_TIMEOUT, Target, command, validate};
use crate::event::HostEvent;
use crate::host::Host;
use crate::native::{canonical_event, native_event};

/// The `timeoutMs` `cargo xtask print-muse-hook` writes by default.
pub const DEFAULT_TIMEOUT_MS: u32 = DEFAULT_TIMEOUT * 1000;

/// The largest `timeoutMs` a Muse entry may declare.
pub const MAX_TIMEOUT_MS: u32 = MAX_TIMEOUT * 1000;

/// The plugin directory that holds the resolver files.
pub const RESOLVER_DIR: &str = "hooks/muse";

/// The interpreter of every resolver; absolute, so `PATH` cannot change it.
const SHELL: &str = "/bin/sh";

/// The resolver's `--plugin-root` value.
const MUSE_ROOT: &str = "\"${MUSE_PLUGIN_ROOT}\"";

/// One `capabilities.hooks` entry of `.muse-plugin/plugin.json`, in Muse's field order.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct MuseEntry {
  /// The hook id: the hook name.
  pub id: String,
  /// The Muse event.
  pub event: String,
  /// `["/bin/sh", "hooks/muse/<name>"]`.
  pub command: Vec<String>,
  /// The host timeout in milliseconds.
  pub timeout_ms: u32,
}

/// One generated Muse hook: its entry and its resolver file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MuseHook {
  /// The manifest entry.
  pub entry: MuseEntry,
  /// The resolver's path relative to the plugin root.
  pub resolver_path: String,
  /// The resolver's text.
  pub resolver: String,
}

/// Generate the Muse hook for `target`.
///
/// # Errors
/// When a name fails its pattern, the event is not a Muse event toolu handles, or
/// `timeout_ms` is outside 1..=600000.
pub fn hook(target: &Target<'_>, timeout_ms: u32) -> Result<MuseHook, String> {
  if !is_event(target.event) {
    return Err(format!(
      "event must be a Muse event toolu handles ({}): {:?}",
      events().join(", "),
      target.event
    ));
  }
  validate(target)?;
  if !(1..=MAX_TIMEOUT_MS).contains(&timeout_ms) {
    return Err(format!(
      "timeoutMs must be 1 to {MAX_TIMEOUT_MS} milliseconds, got {timeout_ms}"
    ));
  }
  let resolver_path = format!("{RESOLVER_DIR}/{}", target.name);
  let resolver = format!(
    "# Generated by cargo xtask print-muse-hook {} {} {}; do not edit.\n{}\n",
    target.plugin,
    target.event,
    target.name,
    command(target, MUSE_ROOT)
  );
  Ok(MuseHook {
    entry: MuseEntry {
      id: target.name.to_owned(),
      event: target.event.to_owned(),
      command: vec![SHELL.to_owned(), resolver_path.clone()],
      timeout_ms,
    },
    resolver_path,
    resolver,
  })
}

/// Whether `event` is a Muse event toolu registers hooks for.
pub fn is_event(event: &str) -> bool {
  canonical_event(Host::Muse, event).is_some()
}

/// The Muse names of the host events, once each, in [`HostEvent::ALL`] order.
fn events() -> Vec<&'static str> {
  let mut names: Vec<&'static str> = Vec::new();
  for name in HostEvent::ALL
    .into_iter()
    .filter_map(|event| native_event(Host::Muse, event))
  {
    if !names.contains(&name) {
      names.push(name);
    }
  }
  names
}

